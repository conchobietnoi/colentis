import { launch, login, tab, addTaskUi, mkUser, sql, ok, finish, sleep } from './helpers.mjs'
console.log('S2: offline, hàng đợi đồng bộ')
const U = await mkUser('Chi Mai')
const a = await launch(); const { page, ctx } = a
await login(page, U.email); await tab(page, 'Hôm nay')
await addTaskUi(page, 'Online1')
await ctx.setOffline(true); await page.waitForTimeout(600)
const pill = await page.evaluate(() => !!document.getElementById('off')?.classList.contains('on') || document.body.innerText.includes('Offline') || document.body.innerText.includes('ngoại tuyến'))
await page.click('[data-act=addtask]:visible'); await page.waitForTimeout(500); await page.fill('#ntitle', 'Offline1'); await page.click('#savet'); await page.waitForTimeout(1500)
const toast = await page.evaluate(() => document.getElementById('toast')?.textContent ?? '')
ok(/chờ đồng bộ/.test(toast), 'thêm việc offline báo "chờ đồng bộ": ' + toast)
ok((await sql(`select count(*)::int n from tasks where owner_id=$1`, [U.id]))[0].n === 1, 'server chưa có việc offline')
await tab(page, 'Lịch'); await page.click('.t:has-text("Online1") .ck'); await page.waitForTimeout(1000)
ok((await sql(`select done from tasks where title='Online1' and owner_id=$1`, [U.id]))[0].done === false, 'tick offline chưa lên server')
await a.page.screenshot({ path: 'e2e/out/s2-offline.png' })
await ctx.setOffline(false); await page.waitForTimeout(5000)
ok((await sql(`select count(*)::int n from tasks where owner_id=$1 and title='Offline1'`, [U.id]))[0].n === 1, 'việc offline được đẩy lên khi có mạng')
ok((await sql(`select done from tasks where title='Online1' and owner_id=$1`, [U.id]))[0].done === true, 'tick offline được đồng bộ')
const q = await page.evaluate(() => localStorage.getItem(Object.keys(localStorage).find((k) => k.startsWith('colentis:queue:')) ?? '') )
ok(!q || q === '[]', 'hàng đợi đã trống')
ok(a.logs.length === 0, 'không lỗi JS: ' + a.logs.join('|').slice(0, 200))
await a.browser.close()
process.exit(await finish() ? 1 : 0)
