import { launch, login, tab, mkUser, sql, CTL, ok, finish, shot } from './helpers.mjs'
console.log('S9: trang admin v2 — tổng quan, gửi thư, thành viên, lịch sử')
const AD = await mkUser('Quản Trị Viên'), B = await mkUser('Bảo Bình'), C = await mkUser('Cẩm Chi')
await sql('update profiles set is_admin=true where id=$1', [AD.id])
const a = await launch(); const { page } = a
await login(page, AD.email)
await tab(page, 'Hồ sơ'); await page.waitForTimeout(600)
await page.click('[data-x=admin]'); await page.waitForTimeout(1500)
ok(await page.isVisible('#pgAdmin .adtabs'), 'có thanh 4 tab admin')
ok((await page.textContent('#pgAdmin .adstats')).includes('Thành viên'), 'Tổng quan có số liệu')
await shot(page, 's9-ov')
// Gửi thư: chọn người, mẫu, quà, gửi
await page.click('.adtabs [data-v=send]'); await page.waitForTimeout(500)
await page.click('[data-x=ato][data-v=some]'); await page.waitForTimeout(300)
await page.click(`.adpp:has-text("Bảo Bình")`); await page.waitForTimeout(300)
ok((await page.textContent('#pgAdmin .card-b h2 em')).includes('1 người'), 'chọn 1 người nhận')
await page.click('[data-x=adp][data-v=cheer]'); await page.waitForTimeout(300)
ok((await page.inputValue('#att')).startsWith('Chúc mừng'), 'mẫu điền tiêu đề')
await page.click('[data-x=agk][data-v=rescue]'); await page.click('[data-x=aga]'); await page.waitForTimeout(300)
ok((await page.textContent('.achips')).includes('thẻ cứu'), 'thêm quà thẻ cứu')
await shot(page, 's9-send')
// nháp được lưu khi mở lại
await page.fill('#att', 'Tiêu đề nháp'); await page.waitForTimeout(200)
ok(await page.evaluate(() => (localStorage.getItem('colentis_adm_draft') || '').includes('Tiêu đề nháp')), 'tự lưu nháp trên máy')
await page.click('[data-x=asend]'); await page.waitForTimeout(500)
await page.click('[data-x=cfok]'); await page.waitForTimeout(2200)
const sent = await sql(`select count(*)::int n from mail_recipients r join mails m on m.id=r.mail_id where m.title='Tiêu đề nháp' and r.user_id=$1`, [B.id])
ok(sent[0].n === 1, 'thư đã gửi cho đúng 1 người')
ok((await sql(`select count(*)::int n from mail_recipients r join mails m on m.id=r.mail_id where m.title='Tiêu đề nháp' and r.user_id=$1`, [C.id]))[0].n === 0, 'người khác không nhận')
// Hẹn giờ
await page.click('.adtabs [data-v=send]'); await page.waitForTimeout(400)
await page.fill('#att', 'Thư hẹn giờ'); await page.fill('#atb', 'Nội dung hẹn giờ cho tất cả')
await page.click('[data-x=asc]'); await page.waitForTimeout(300)
const d = new Date(Date.now() + 3 * 86400e3); const loc = new Date(d.getTime() - d.getTimezoneOffset() * 60000).toISOString().slice(0, 16)
await page.fill('#adt', loc); await page.dispatchEvent('#adt', 'change')
await page.click('[data-x=asend]'); await page.waitForTimeout(500); await page.click('[data-x=cfok]'); await page.waitForTimeout(2200)
ok((await sql(`select count(*)::int n from mails where title='Thư hẹn giờ'`))[0].n === 1, 'thư hẹn giờ đã tạo')
ok(await page.isVisible('.adit:has-text("Thư hẹn giờ")'), 'thư hẹn giờ hiện ở tab Lịch sử')
await shot(page, 's9-hist')
// Huỷ hẹn
await page.click('[data-x=adx]'); await page.waitForTimeout(400); await page.click('[data-x=cfok]'); await page.waitForTimeout(2000)
ok((await sql(`select count(*)::int n from mails where title='Thư hẹn giờ'`))[0].n === 0, 'huỷ hẹn xoá thư')
// Thành viên
await page.click('.adtabs [data-v=mem]'); await page.waitForTimeout(500)
ok((await page.$$('.adm')).length >= 3, 'danh sách thành viên')
await page.fill('#amq', 'Cẩm'); await page.waitForTimeout(300)
ok((await page.$$('.adm')).length === 1, 'tìm thành viên theo tên')
await shot(page, 's9-mem')
await page.click('[data-x=admn]'); await page.waitForTimeout(500)
ok((await page.inputValue('#att')).includes('Nhắc điểm danh'), 'Nhắc điểm danh điền sẵn mẫu và chuyển sang tab Gửi thư')
// Người thường không vào được RPC
const r = await B.call('admin_overview', {}); ok(!r.ok, 'người thường bị chặn khỏi hàm admin')
await finish()
